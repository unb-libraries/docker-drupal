#!/usr/bin/env sh
# Stamp the deployment identifier (the downstream site's build/commit id) so Drupal
# invalidates its compiled service container, APCu, and Twig caches on each deploy.
#
# The value is written as a literal into a dedicated include regenerated each boot;
# settings.php gets a one-time guarded require_once of it. This keeps the volatile
# value in a per-pod file (no shared-volume drift, no rolling-update conflict, no
# regex, no collision with default.settings.php's commented example) and works for
# php-fpm AND drush CLI without depending on getenv()/clear_env.
#
# DRUPAL_DEPLOYMENT_IDENTIFIER is baked into site images from the VERSION build-arg
# (<short-commit>-<timestamp>) via ONBUILD in the UNB base image. Unset => no-op.

SETTINGS_FILE="$DRUPAL_ROOT/sites/default/settings.php"
MANAGED_INCLUDE="$DRUPAL_ROOT/sites/all/settings/deployment_identifier.settings.php"

[ -f "$SETTINGS_FILE" ] || exit 0

if [ -n "$DRUPAL_DEPLOYMENT_IDENTIFIER" ]; then
  # Defensive: identifier is expected to be [A-Za-z0-9._-]; strip anything else so it
  # can never break out of the single-quoted PHP string literal.
  SAFE_ID=$(printf '%s' "$DRUPAL_DEPLOYMENT_IDENTIFIER" | tr -cd 'A-Za-z0-9._-')
  printf "<?php\n\n// Generated by pre-init.d/62_set_deployment_identifier.sh - do not edit.\n\$settings['deployment_identifier'] = '%s';\n" \
    "$SAFE_ID" > "$MANAGED_INCLUDE"
  chmod 644 "$MANAGED_INCLUDE"   # readable by the web user regardless of umask
  echo "[i] deployment_identifier set to '$SAFE_ID'"
else
  rm -f "$MANAGED_INCLUDE"
  echo "[i] DRUPAL_DEPLOYMENT_IDENTIFIER unset; deployment_identifier not stamped"
fi

# Wire the include into settings.php exactly once. Guard matches the FILENAME (never
# collides with the commented '$settings['deployment_identifier']' example). The
# leading newline guards a settings.php not ending in one; require_once + file_exists
# keep a one-time concurrent append (web + cron pods share the volume) harmless.
grep -q -F 'deployment_identifier.settings.php' "$SETTINGS_FILE" || {
  printf '\n'
  cat <<'PHP'
if (file_exists(DRUPAL_ROOT . '/sites/all/settings/deployment_identifier.settings.php')) {
  require_once DRUPAL_ROOT . '/sites/all/settings/deployment_identifier.settings.php';
}
PHP
} >> "$SETTINGS_FILE"
